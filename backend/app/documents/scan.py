"""Compose one upload from bounded, ordered camera images."""

import asyncio
from collections.abc import Sequence
from io import BytesIO

from pypdf import PdfReader, PdfWriter

from app.config import settings
from app.documents.images import normalize_image
from app.documents.validation import UnsupportedDocumentFormatError, validate_document_content


class ScanTooLargeError(ValueError):
    """The uploaded or composed scan exceeds its configured limit."""


def scan_page_limit() -> int:
    return min(settings.DOCUMENT_SCAN_MAX_PAGES, settings.DOCUMENT_MAX_PAGES)


def _join_pages(pages: Sequence[bytes]) -> bytes:
    # Each input was generated by the bounded image decoder, not supplied as a PDF.
    writer = PdfWriter()
    for content in pages:
        writer.add_page(PdfReader(BytesIO(content)).pages[0])
    output = BytesIO()
    writer.write(output)
    if output.tell() > settings.DOCUMENT_MAX_FILE_BYTES:
        raise ScanTooLargeError
    return output.getvalue()


async def assemble_scan(images: Sequence[tuple[bytes, str]]) -> bytes:
    if not 2 <= len(images) <= scan_page_limit():
        raise ScanTooLargeError
    if sum(len(content) for content, _ in images) > settings.DOCUMENT_MAX_FILE_BYTES:
        raise ScanTooLargeError
    pages = []
    pdf_bytes = 0
    for content, declared_mime in images:
        if not content:
            raise UnsupportedDocumentFormatError("Empty scan page", code="document_empty")
        mime = await validate_document_content(content, declared_mime)
        if mime not in {"image/jpeg", "image/png", "image/heif"}:
            raise UnsupportedDocumentFormatError(
                "Only images can be used as scan pages", code="document_mime_unsupported"
            )
        page = await normalize_image(content, mime, as_pdf=True)
        pdf_bytes += len(page)
        if pdf_bytes > settings.DOCUMENT_MAX_FILE_BYTES:
            raise ScanTooLargeError
        pages.append(page)
    return await asyncio.to_thread(_join_pages, pages)
